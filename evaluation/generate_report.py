"""Runs every eval and writes evaluation/EVAL_RESULTS.md from real return values.

Run this on a network-capable machine with Ollama up (see evaluation/README.md
"Development & data policy"). Nothing here is hand-edited - the markdown is
produced entirely from live eval output.

    python -m evaluation.generate_report
"""

import datetime as _dt
import os

from dotenv import load_dotenv

load_dotenv()

OUTPUT_PATH = os.path.join("evaluation", "EVAL_RESULTS.md")


def _section(title, body):
    return f"## {title}\n\n{body}\n"


def _retrieval_section():

    from evaluation.retrieval_eval import compute_metrics, compare_k_configs

    baseline = compute_metrics()
    comparison = compare_k_configs()

    lines = [
        "| Metric | Value |",
        "|---|---|",
        f"| n_examples | {baseline['n_examples']} |",
        f"| k | {baseline['k']} |",
        f"| recall_at_k | {baseline['recall_at_k']:.3f} |",
        f"| precision_at_k | {baseline['precision_at_k']:.3f} |",
        f"| mrr | {baseline['mrr']:.3f} |",
        "",
        "### Comparison run (varying k)",
        "",
        "| k | recall_at_k | precision_at_k | mrr |",
        "|---|---|---|---|",
    ]

    for row in comparison:
        lines.append(
            f"| {row['k']} | {row['recall_at_k']:.3f} | "
            f"{row['precision_at_k']:.3f} | {row['mrr']:.3f} |"
        )

    return "\n".join(lines)


def _generation_section():

    from evaluation.generation_eval import run_generation_eval, hallucinated_visa_case

    # sample_size=0 forces the full 45 regardless of a stray EVAL_SAMPLE_SIZE
    # env var - the honesty rule requires the official report reflect the
    # full golden set, never the fast/demo subset.
    summary = run_generation_eval(sample_size=0)
    hallucination = hallucinated_visa_case()

    return "\n".join([
        "| Metric | Value |",
        "|---|---|",
        f"| n_examples | {summary['n_examples']} |",
        f"| avg_faithfulness_score | {summary['avg_faithfulness_score']:.2f} / 5 |",
        f"| n_visa_examples | {summary['n_visa_examples']} |",
        f"| avg_visa_faithfulness_score | {summary['avg_visa_faithfulness_score']:.2f} / 5 |",
        f"| hallucinated_visa_case caught | "
        f"{not hallucination['faithful']} (score={hallucination['score']}) |",
    ])


def _scenario_section():

    from evaluation.scenario_eval import run_all_scenarios

    results = run_all_scenarios()

    lines = [
        "| scenario_name | expected | actual | match |",
        "|---|---|---|---|",
    ]

    for r in results:
        mark = "✅" if r["match"] else "❌"
        lines.append(
            f"| {r['scenario_name']} | {r['expected_outcome']} | "
            f"{r['actual_outcome']} | {mark} |"
        )

    passed = sum(1 for r in results if r["match"])
    lines.append("")
    lines.append(f"**{passed}/{len(results)} scenarios matched expected outcome.**")

    return "\n".join(lines)


def build_report():

    sections = [
        ("1. Retrieval evaluation", _retrieval_section),
        ("2. Generation evaluation (LLM-as-judge)", _generation_section),
        ("3. End-to-end scenario evaluation", _scenario_section),
    ]

    parts = [
        "# TripPilot — Evaluation Results (auto-generated)",
        "",
        "> Generated by `python -m evaluation.generate_report`. Do not edit by "
        "hand — re-run the generator instead. Methodology and how-to live in "
        "`evaluation/README.md`.",
        "",
        f"_Generated: {_dt.datetime.now().isoformat(timespec='seconds')}_",
        "",
    ]

    for title, fn in sections:
        try:
            body = fn()
        except Exception as exc:
            body = f"⚠️ Eval did not run: `{exc}`"
        parts.append(_section(title, body))

    return "\n".join(parts)


if __name__ == "__main__":
    report = build_report()
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write(report)
    print(f"Wrote {OUTPUT_PATH}")
